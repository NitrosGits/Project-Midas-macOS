#!/usr/bin/env python3
"""
gen_static_dl_relocs.py - static relocations for the host addresses in a
file's static display lists.

A GE_64BIT build can't put a host address into a static gs* command: the word
is 32 bits and the address is only known as a window word at boot. A file that
defines PORT_STATIC_DL_RELOCS (before its includes) gets 0 for every such
operand (gbi.h GBI_SADDR), and this script writes the matching
PORT_STATIC_PTR32 records, which portWindowInit applies at boot:

  PORT_STATIC_PTR32(DL_0x0018[12].words.w1, &img_0x0020);

It finds the operands with clang's AST of the file as an i386 build (where the
gs* operands are plain casts), so the element index of every command is the
compiler's own, however many commands a macro expands to. Include the output
at the end of the source file under #ifdef GE_64BIT. Rerun it whenever the
display lists change; --check fails if the file on disk is stale.

Usage (from the repository root):
  python3 scripts/port/gen_static_dl_relocs.py build_mac assets/rarewarelogo.c [--check]
"""
import argparse
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ptr32_check  # noqa: E402  (compile database and i386 flags)

ROOT = ptr32_check.ROOT
GFX_ARRAY = re.compile(r"^(?:static\s+)?Gfx\s+(\w+)\s*\[[^\]]*\]\s*=", re.M)


def ast_for(entry, src, name):
    base, s = ptr32_check.i386_args(entry, ROOT, ROOT)
    base = [x for x in base if not x.startswith('-D') or x != '-DPORT_STATIC_DL_RELOCS']
    r = subprocess.run(base + ['-fsyntax-only', '-Xclang', '-ast-dump=json',
                               '-Xclang', '-ast-dump-filter=' + name, s],
                       cwd=entry['directory'], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit('%s: clang failed:\n%s' % (src, r.stderr[:2000]))
    # one JSON object per matching decl, separated by "Dumping <name>:" lines
    out = []
    for chunk in re.split(r'^Dumping [^\n]*:\n', r.stdout, flags=re.M):
        chunk = chunk.strip()
        if chunk:
            out.append(json.loads(chunk))
    return out


def refs(node, parent_op=None, found=None):
    """(name, address-of?) for every variable or function the subtree names"""
    if found is None:
        found = []
    if node.get('kind') == 'DeclRefExpr':
        d = node.get('referencedDecl', {})
        if d.get('kind') in ('VarDecl', 'FunctionDecl'):
            found.append((d['name'], parent_op == '&'))
    op = node.get('opcode') if node.get('kind') == 'UnaryOperator' else None
    for c in node.get('inner', []):
        if c.get('kind') in ('UnaryExprOrTypeTraitExpr',):
            continue  # sizeof(...) names no address
        refs(c, op, found)
    return found


def relocs_for(decl):
    """[(index, target)] for one Gfx array VarDecl"""
    init = next((c for c in decl.get('inner', []) if c.get('kind') == 'InitListExpr'), None)
    if init is None:
        return []
    out = []
    for i, elem in enumerate(init.get('inner', [])):
        # Gfx is a union whose first member is Gwords {w0, w1}
        words = elem
        while words.get('kind') == 'InitListExpr' and len(words.get('inner', [])) == 1:
            words = words['inner'][0]
        inner = words.get('inner', [])
        if words.get('kind') != 'InitListExpr' or len(inner) < 2:
            if refs(elem):
                sys.exit('%s[%d]: an address outside a {w0, w1} command' % (decl['name'], i))
            continue
        if refs(inner[0]):
            sys.exit('%s[%d]: an address in w0' % (decl['name'], i))
        found = sorted(set(refs(inner[1])))
        if not found:
            continue
        if len(found) != 1:
            sys.exit('%s[%d]: w1 names %s; only one symbol is supported' % (decl['name'], i, found))
        name, addr = found[0]
        out.append((i, ('&' if addr else '') + name))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('build_dir')
    ap.add_argument('source')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()

    src = os.path.realpath(args.source)
    entry = next((e for e in ptr32_check.compdb(args.build_dir)
                  if os.path.realpath(e['file']) == src), None)
    if entry is None:
        sys.exit('%s is not in the compile database' % args.source)
    names = GFX_ARRAY.findall(open(src).read())
    lines = ['/* Generated by scripts/port/gen_static_dl_relocs.py from %s: do not edit.' % os.path.basename(src),
             ' * The host addresses in its static display lists, filled in at boot',
             ' * (GE_64BIT; see gbi.h GBI_SADDR). */']
    total = 0
    for name in names:
        decls = [d for d in ast_for(entry, src, name)
                 if d.get('kind') == 'VarDecl' and d.get('name') == name and d.get('inner')]
        if len(decls) != 1:
            sys.exit('%s: %d definitions of %s in the AST' % (src, len(decls), name))
        for i, target in relocs_for(decls[0]):
            lines.append('PORT_STATIC_PTR32(%s[%d].words.w1, %s);' % (name, i, target))
            total += 1
    text = '\n'.join(lines) + '\n'
    out = os.path.splitext(src)[0] + '.relocs.inc'  # not *.c: CMake globs src/*.c
    if args.check:
        cur = open(out).read() if os.path.exists(out) else ''
        if cur != text:
            sys.exit('%s is stale: rerun gen_static_dl_relocs.py' % os.path.relpath(out, ROOT))
        print('%s: up to date (%d records)' % (os.path.relpath(out, ROOT), total))
        return
    with open(out, 'w') as fp:
        fp.write(text)
    print('%s: %d records from %d display lists' % (os.path.relpath(out, ROOT), total, len(names)))


if __name__ == '__main__':
    main()
